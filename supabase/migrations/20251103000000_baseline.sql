CREATE OR REPLACE FUNCTION public.get_top_customers_by_rejects(start_date timestamp with time zone, end_date timestamp with time zone)
 RETURNS TABLE(customer_id integer, customer_name text, logo text, total_defects integer)
 LANGUAGE sql
AS $function$
  select
    c.id as customer_id,
    c.display_name as customer_name,
    c.logo,
    sum(n.quantity_defective) as total_defects
  from "NCM" n
  join "Customers" c on n.customer = c.id
  join "Status" s on n.status = s.id
  where
    s.type != 'omit' and
    n.date between start_date and end_date
  group by c.id, c.name, c.logo
  order by total_defects desc
  limit 5;
$function$;

CREATE OR REPLACE FUNCTION public.get_user_notifications(user_id uuid)
 RETURNS TABLE(id uuid, title text, body text, meta_data jsonb, doc_ref text, read boolean, delivered_at timestamp without time zone, created_by text, avatar text)
 LANGUAGE sql
AS $function$
  select
    nr.id,
    n.title,
    n.body,
    n.meta_data,
    n.doc_ref,
    nr.read,
    nr.delivered_at,
    e.first_name || ' ' || e.surname as created_by,
    e.avatar
  from "Notification Recipients" nr
  join "Notifications" n on n.id = nr.notification_id
  join "Employees" e on e.auth_id = n.created_by
  where nr.recipient_id = user_id
  order by n.created_at desc
$function$;

