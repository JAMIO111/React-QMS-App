CREATE OR REPLACE FUNCTION public.get_aggregated_defects(start_date timestamp with time zone, end_date timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
declare
  range_days integer;
  interval_unit text;
  result jsonb;
begin
  range_days := date_part('day', end_date - start_date);

  if range_days <= 1 then
    interval_unit := 'hour';
  elsif range_days <= 7 then
    interval_unit := 'day';
  elsif range_days <= 90 then
    interval_unit := 'week';
  elsif range_days <= 365 then
    interval_unit := 'month';
  else
    interval_unit := 'quarter';
  end if;

  execute format($f$
    select jsonb_agg(row_to_json(t)) from (
      select
        date_trunc('%I', date) as period,
        sum(quantity_defective) as total_quantity
      from "NCM"
      where date between $1 and $2
      group by period
      order by period
    ) t
  $f$, interval_unit)
  into result
  using start_date, end_date;

  return coalesce(result, '[]'::jsonb);
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_nc_date_trend(start_date timestamp with time zone, end_date timestamp with time zone, override_period text DEFAULT NULL::text, nc_type text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
declare
  range_days integer;
  interval_unit text;
  step text;
  result jsonb;
  filter_condition text := '';
begin
  range_days := date_part('day', end_date - start_date);

  if override_period is not null then
    interval_unit := lower(override_period);
  else
    if range_days <= 1 then
      interval_unit := 'hour';
    elsif range_days <= 7 then
      interval_unit := 'day';
    elsif range_days <= 90 then
      interval_unit := 'week';
    elsif range_days <= 365 then
      interval_unit := 'month';
    else
      interval_unit := 'quarter';
    end if;
  end if;

  step := case interval_unit
    when 'hour' then '1 hour'
    when 'day' then '1 day'
    when 'week' then '1 week'
    when 'month' then '1 month'
    when 'quarter' then '3 month'
    when 'year' then '1 year'
    else '1 day'
  end;

  if nc_type is not null then
    filter_condition := format('and n.type = %L', nc_type);
  end if;

  execute format($f$
    with periods as (
      select generate_series(
        date_trunc('%1$I', $1),
        date_trunc('%1$I', $2),
        interval '%2$s'
      ) as period
    ),
    data as (
      select
        date_trunc('%1$I', n.date) as period,
        count(*) as record_count,
        sum(n.quantity_defective) as total_quantity,
        sum(n.total_cost) as total_cost
      from "NCM" n
      join "Status" s on n.status = s.id
      where n.date between $1 and $2
        and s.type != 'omit'
        %3$s
      group by 1
    )
    select jsonb_agg(jsonb_build_object(
      'period', p.period,
      'label', to_char(p.period, case
        when '%1$I' = 'hour' then 'HH24:00 Mon DD'
        when '%1$I' = 'day' then 'DD Mon'
        when '%1$I' = 'week' then '"Week "IW YYYY'
        when '%1$I' = 'month' then 'Mon YYYY'
        when '%1$I' = 'quarter' then '"Q"Q YYYY'
        else 'YYYY'
      end),
      'record_count', coalesce(d.record_count, 0),
      'total_quantity', coalesce(d.total_quantity, 0),
      'total_cost', coalesce(d.total_cost, 0)
    ))
    from periods p
    left join data d on p.period = d.period
  $f$, interval_unit, step, filter_condition)
  into result
  using start_date, end_date;

  return coalesce(result, '[]'::jsonb);
end;
$function$;

