    c.name as customer_name,
    ncm.failure_mode,
    fm.name as failure_mode_name,
    ncm.sub_failure_mode,
    sfm.name as sub_failure_mode_name,
    ncm.status,
    st.name as status_name,
    ncm.causal_process,
    p1.name as causal_process_name,
    ncm.location_detected,
    p2.name as location_detected_name,
    case when nc_type = 'Supplier' then null else ncm.responsible_operator end as responsible_operator,
    ncm.supplier,
    s.name as supplier_name,
    s.display_name as supplier_display_name,
    ncm.description,
    ncm.total_cost,
    ncm.ref_8d,
    case when nc_type = 'Supplier' then ncm.purchase_order else null end as purchase_order
  from "NCM" ncm
  left join "Customers" c on ncm.customer = c.id
  left join "Suppliers" s on ncm.supplier = s.id
  left join "Failure Mode" fm on ncm.failure_mode = fm.id
  left join "Sub-Failure Mode" sfm on ncm.sub_failure_mode = sfm.id
  left join "Status" st on ncm.status = st.id
  left join "Process" p1 on ncm.causal_process = p1.id
  left join "Process" p2 on ncm.location_detected = p2.id
  where ncm.type = nc_type;
$function$;

CREATE OR REPLACE FUNCTION public.get_ncm_summary_json(start_date timestamp with time zone, end_date timestamp with time zone)
 RETURNS json
 LANGUAGE sql
AS $function$
  with filtered_ncm as (
    select n.*, s.type as status_type
    from "NCM" n
    join "Status" s on n.status = s.id
    where s.type != 'omit'
      and n.date between start_date and end_date
  ),
  top_customers as (
    select
      c.id as customer_id,
      c.display_name as customer_name,
      c.logo,
      sum(n.quantity_defective) as total_defects
    from filtered_ncm n
    join "Customers" c on n.customer = c.id
    group by c.id, c.display_name, c.logo
    order by total_defects desc
    limit 5
  ),
  totals as (
    select jsonb_build_object(
      'total_cost', coalesce(sum(total_cost), 0),
      'total_quantity', coalesce(sum(quantity_defective), 0),
      'record_count', count(*)
    ) as data
    from filtered_ncm
  ),
  customers_json as (
    select jsonb_agg(tc) as data
    from top_customers tc
  )
  select jsonb_build_object(
    'top_customers', customers_json.data,
    'totals', totals.data
  )
  from customers_json, totals;
$function$;

