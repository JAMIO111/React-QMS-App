CREATE OR REPLACE FUNCTION public.get_nc_kpi_json(start_date timestamp with time zone, end_date timestamp with time zone)
 RETURNS json
 LANGUAGE sql
AS $function$
  with filtered_ncm as (
    select n.*, s.type as status_type
    from "NCM" n
    join "Status" s on n.status = s.id
    where s.type != 'omit'
      and n.date between start_date and end_date
  ),
  top_customers as (
    select
      c.id as customer_id,
      c.display_name as customer_name,
      c.logo,
      sum(n.quantity_defective) as total_defects
    from filtered_ncm n
    join "Customers" c on n.customer = c.id
    group by c.id, c.display_name, c.logo
    order by total_defects desc
    limit 5
  ),
  totals as (
    select jsonb_build_object(
      'total_cost', coalesce(sum(total_cost), 0),
      'total_quantity', coalesce(sum(quantity_defective), 0),
      'record_count', count(*)
    ) as data
    from filtered_ncm
  ),
  customers_json as (
    select jsonb_agg(tc) as data
    from top_customers tc
  )
  select jsonb_build_object(
    'top_customers', customers_json.data,
    'totals', totals.data
  )
  from customers_json, totals;
$function$;

CREATE OR REPLACE FUNCTION public.get_nc_kpi_json(start_date timestamp with time zone, end_date timestamp with time zone, nc_type text)
 RETURNS json
 LANGUAGE sql
AS $function$
with
periods as (
  select
    start_date,
    end_date,
    end_date - start_date as duration,
    start_date - (end_date - start_date) as prev_start,
    end_date - (end_date - start_date) as prev_end
),
current_ncm as (
  select n.*, s.type as status_type
  from "NCM" n
  join "Status" s on n.status = s.id
  join periods p on true
  where s.type != 'omit'
    and n.type = nc_type
    and n.date between p.start_date and p.end_date
),
previous_ncm as (
  select n.*, s.type as status_type
  from "NCM" n
  join "Status" s on n.status = s.id
  join periods p on true
  where s.type != 'omit'
    and n.type = nc_type
    and n.date between p.prev_start and p.prev_end
),
top_entities as (
  select
    case when nc_type = 'Supplier' then sup.id else c.id end as entity_id,
    case when nc_type = 'Supplier' then sup.display_name else c.display_name end as entity_name,
    case when nc_type = 'Supplier' then sup.logo else c.logo end as entity_logo,
    sum(n.quantity_defective) as total_defects
  from current_ncm n
  left join "Customers" c on n.customer = c.id and nc_type != 'Supplier'
  left join "Suppliers" sup on n.supplier = sup.id and nc_type = 'Supplier'
  group by entity_id, entity_name, entity_logo
  order by total_defects desc
  limit 5
),
top_causal_processes as (
  select
    cp.id as process_id,
    cp.name as process_name,
    cp.code,
    sum(n.quantity_defective) as total_defects
  from current_ncm n
  join "Process" cp on n.causal_process = cp.id
  group by cp.id, cp.name, cp.code
  order by total_defects desc
  limit 5
),
current_totals as (
  select
    coalesce(sum(total_cost), 0) as total_cost,
    coalesce(sum(quantity_defective), 0) as total_quantity,
    count(*) as record_count
  from current_ncm
),
previous_totals as (
  select
    coalesce(sum(total_cost), 0) as total_cost,
    coalesce(sum(quantity_defective), 0) as total_quantity,
    count(*) as record_count
  from previous_ncm
),
totals as (
  select jsonb_build_object(
    'total_cost', c.total_cost,
    'total_quantity', c.total_quantity,
    'record_count', c.record_count,
    'cost_change_pct', case
      when p.total_cost = 0 and c.total_cost = 0 then 0
      when p.total_cost = 0 then null
      else round(100.0 * (c.total_cost - p.total_cost) / p.total_cost, 2)
    end,
    'quantity_change_pct', case
      when p.total_quantity = 0 and c.total_quantity = 0 then 0
      when p.total_quantity = 0 then null
      else round(100.0 * (c.total_quantity - p.total_quantity) / p.total_quantity, 2)
    end,
    'record_count_change_pct', case
      when p.record_count = 0 and c.record_count = 0 then 0
      when p.record_count = 0 then null
      else round(100.0 * (c.record_count - p.record_count) / p.record_count, 2)
    end
  ) as data
  from current_totals c, previous_totals p
),
entities_json as (
  select jsonb_agg(te) as data
  from top_entities te
),
causal_processes_json as (
  select jsonb_agg(jsonb_build_object(
    'process_id', process_id,
    'process_name', process_name,
    'code', code,
    'total_defects', total_defects
  )) as data
  from top_causal_processes
),
fm_sfm_quantities_grouped as (
  select jsonb_agg(jsonb_build_object(
    'failure_mode_id', fm.failure_mode_id,
    'failure_mode', fm.failure_mode_name,
    'total_quantity', fm.total_quantity,
    'sub_failure_modes', fm.subs
  )) as data
  from (
    with grouped_subs as (
      select
        n.failure_mode as failure_mode_id,
        fm.name as failure_mode_name,
        n.sub_failure_mode as sub_failure_mode_id,
        sfm.name as sub_failure_mode_name,
        sum(n.quantity_defective) as quantity
      from current_ncm n
      join "Failure Mode" fm on n.failure_mode = fm.id
      join "Sub-Failure Mode" sfm on n.sub_failure_mode = sfm.id
      group by n.failure_mode, fm.name, n.sub_failure_mode, sfm.name
    )
    select
      failure_mode_id,
      failure_mode_name,
      sum(quantity) as total_quantity,
      jsonb_agg(
        jsonb_build_object(
          'sub_failure_mode_id', sub_failure_mode_id,
          'sub_failure_mode', sub_failure_mode_name,
          'quantity', quantity
        )
        order by quantity desc
      ) as subs
    from grouped_subs
    group by failure_mode_id, failure_mode_name
  ) fm
),
top_parts as (
  select jsonb_agg(jsonb_build_object(
    'part_number', rp.part_number,
    'part_name', rp.part_name,
    'total_defects', rp.total_defects
  ) order by rp.total_defects desc) as data
  from (
    select
      p.part_number,
      p.name as part_name,
      sum(n.quantity_defective) as total_defects
    from current_ncm n
    join "Part" p on n.part_number = p.id
    group by p.part_number, p.name
    order by total_defects desc
    limit 5
  ) rp
)
select jsonb_build_object(
  'top_entities', entities_json.data,
  'top_causal_processes', causal_processes_json.data,
  'totals', totals.data,
  'failure_mode_breakdown', fm_sfm_quantities_grouped.data,
  'top_parts', top_parts.data
)
from entities_json, causal_processes_json, totals, fm_sfm_quantities_grouped, top_parts;
$function$;

